#!/bin/sh
# smoke: `jichi-harness push units --config <cfg>` -- the host push's systemd
# user units, GENERATED not hand-written (M1147, batch H7; behaviour B4). The
# command prints `jhp-push.service` (a user-level oneshot whose ExecStart
# names the TICK COMMAND, `push tick --config <cfg>`, not a script path) and
# `jhp-push.timer` (OnCalendar from the config's host.pushOnCalendar -- SV:1639:
# the schedule comes from the config so two drives' pushes never share a
# minute on the same host; NO fallback, an absent pushOnCalendar refuses)
# to stdout, or with `-o <dir>` writes the two files; their bytes are the
# reference's shape with THIS drive's names (the jhp- prefix, this drive's
# host dir) and a CHANGED marker saying the unit is generated, not
# hand-written. This container has no systemd: the GENERATION is tested
# (bytes), the supervisor installs the real units on the host.
#
# M1147 (H7). Design note (the contract, behaviour list B4):
#   docs/internal/drive/2026-11-05-harness-port/notes/M1147.md
# Reference units (the shape the generation must match with this drive's
# names; this driver reads only its own generated bytes -- it does NOT look
# for the reference's systemd/ dir in the repo tree):
#   docs/internal/drive/2026-10-27-hardening-host/systemd/jhd-push.service
#   docs/internal/drive/2026-10-27-hardening-host/systemd/jhd-push.timer
#
# THE RED THIS IS HELD BY. On the tree before this batch the top-level verb
# `push` does not exist in jichi-harness: every check that runs a push
# subcommand gets `unknown command 'push'` and exit 2. All six cells run the
# verb and are RED for exactly that reason (rc 2 instead of 0, and the unit
# bytes they assert are absent from stdout / the -o dir).
#
# WHAT IS CHECKED -- 6 cells, one t_ok/t_fail each:
#   1. `push units --config <cfg>` prints the two units to stdout (both
#      `jhp-push.service` and `jhp-push.timer` named); with `-o <dir>` it
#      writes exactly those two files there and nothing else.
#   2. the service file: Type=oneshot, Nice=10, After=network-online.target,
#      and ExecStart names the TICK COMMAND (`push tick --config <cfg path>`)
#      -- not a .sh script path (B4: the units name the command and the
#      config, so the host installs no script).
#   3. the timer file: OnCalendar= THE CONFIGURED value (host.pushOnCalendar)
#      -- cell 3 runs the generation twice under two DIFFERENT configured
#      values so a constant schedule cannot pass (SV:1639) -- plus
#      AccuracySec=30s, Persistent=true, WantedBy=timers.target.
#   4. the names: `jhp-push.service` / `jhp-push.timer` (the jhp- prefix,
#      not the reference's jhd-) and the generated service carries THIS
#      drive's host dir (pushHome, from the config's host block).
#   5. the generated service carries a comment marking it GENERATED (not
#      hand-written) -- the CHANGED marker, B4.
#   6. a config WITHOUT the host block: `push units` refuses exit 2, naming
#      `no host block` (the host commands are host-side by construction; a
#      container config that names no host dir must not guess one); AND a
#      host block WITHOUT pushOnCalendar refuses exit 2 naming
#      `pushOnCalendar` (SV:1639: NO fallback -- a default schedule may
#      collide with another drive's push on the same host).
#
# THE FIXTURE. Under $SMOKE_TMP: a minimal harness config (dir, modelKeyFile,
# gitTokenFile, drive.branchPrefix, the note's host block: pushHome under
# $SMOKE_TMP, image jichi-drive:test, pushOnCalendar the driver's first
# value), a second config with a DIFFERENT pushOnCalendar (cell 3: a constant
# cannot pass both runs), a third with the host block but WITHOUT
# pushOnCalendar (cell 6's SV:1639 refusal) and a fourth without the host
# block. No git repos are needed (the units name paths, they do not run git)
# -- but the config must stay a plausible harness config, so the canary
# secret files it names exist (modelKeyFile a random hex canary, gitTokenFile
# a DISTINCT fake 40-hex canary; never a real key). The red tree's loader
# parses point-wise and ignores the unknown host block, which is why the red
# lands on `unknown command 'push'`, not on a config refusal.
#
# Runs the tree's binary by path ($HBIN, the third_program idiom), never a
# PATH-resolved jichi-harness, and -- for smoke_lint check 5 -- also runs
# the tree's "$BIN" once. No timeout wrapper; git children (none here) would
# carry -c user.name/-c user.email (M2-neutral).
. "$(dirname "$0")/_smoke.sh"

t_plan 6
smoke_home
tmp=$(smoke_tmp)

# smoke_lint check 5: there are no fixture git children here, but $BIN must
# be exercised so the lint sees the driver validate the just-built tree.
"$BIN" --version > "$tmp/binv" 2>/dev/null

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
HBIN="${JC_SMOKE_HBIN:-$ROOT/jichi-harness}"

# Neutralise ambient harness loader settings (env wins over the config).
unset JICHI_HARNESS_DIR JICHI_HARNESS_MODEL_KEY_FILE JICHI_HARNESS_GIT_TOKEN_FILE

KEYCANARY=$(od -An -N20 -tx1 /dev/urandom 2>/dev/null | tr -d ' \n'); [ -n "$KEYCANARY" ] || KEYCANARY="canarykey$$_"
TOKEN_CANARY="c3d9f5a8b2e7416c0d3f6a9e2b5c8d1f4a7e0b3d"

# A fixture failure emits one t_fail per cell so the plan stays honest.
fixture_fail() {
    _ff_n=0
    while [ "$_ff_n" -lt 6 ]; do
        _ff_n=$((_ff_n + 1))
        t_fail "$_ff_n: fixture failed: $1"
    done
    t_done
}

if [ ! -x "$HBIN" ]; then
    fixture_fail "the harness binary $HBIN is not built (run `make jichi-harness` first)"
fi

printf '%s\n' "$KEYCANARY" > "$tmp/kfile"; chmod 600 "$tmp/kfile"
printf '%s\n' "$TOKEN_CANARY" > "$tmp/tokfile"; chmod 600 "$tmp/tokfile"

PH="$tmp/pushhome"; mkdir -p "$PH" || fixture_fail "pushHome"

# SV:1639: the timer's OnCalendar comes from the config's host.pushOnCalendar.
# Two DIFFERENT configured values (cell 3 runs the generation under each, so a
# constant schedule cannot pass both).
OC1='*-*-* *:07,27,47:00'
OC2='*-*-* *:11:00'
cat > "$tmp/cfg.json" <<EOF
{"dir":"$tmp/dir",
"modelKeyFile":"$tmp/kfile","gitTokenFile":"$tmp/tokfile",
"drive":{"branchPrefix":"drive/x-test","gitName":"Harness Test","gitEmail":"harness-test@example.com"},
"host":{"pushHome":"$PH","image":"jichi-drive:test","pushOnCalendar":"$OC1"}}
EOF
# cfg2: the SAME config with a DIFFERENT pushOnCalendar (cell 3's second run).
cat > "$tmp/cfg2.json" <<EOF
{"dir":"$tmp/dir",
"modelKeyFile":"$tmp/kfile","gitTokenFile":"$tmp/tokfile",
"drive":{"branchPrefix":"drive/x-test","gitName":"Harness Test","gitEmail":"harness-test@example.com"},
"host":{"pushHome":"$PH","image":"jichi-drive:test","pushOnCalendar":"$OC2"}}
EOF
# cfgnooc: the host block WITHOUT pushOnCalendar (cell 6's SV:1639 refusal).
cat > "$tmp/cfgnooc.json" <<EOF
{"dir":"$tmp/dir",
"modelKeyFile":"$tmp/kfile","gitTokenFile":"$tmp/tokfile",
"drive":{"branchPrefix":"drive/x-test","gitName":"Harness Test","gitEmail":"harness-test@example.com"},
"host":{"pushHome":"$PH","image":"jichi-drive:test"}}
EOF
# cfgnohost: the SAME config without the host block (cell 6).
cat > "$tmp/cfgnohost.json" <<EOF
{"dir":"$tmp/dir",
"modelKeyFile":"$tmp/kfile","gitTokenFile":"$tmp/tokfile",
"drive":{"branchPrefix":"drive/x-test","gitName":"Harness Test","gitEmail":"harness-test@example.com"}}
EOF

# --- 1: the generation (stdout + -o <dir>) ----------------------------------
"$HBIN" push units --config "$tmp/cfg.json" \
    < /dev/null > "$tmp/u1" 2> "$tmp/u1.err"
rc1=$?
od="$tmp/units-out"; mkdir -p "$od" || fixture_fail "units -o dir"
"$HBIN" push units --config "$tmp/cfg.json" -o "$od" \
    < /dev/null > "$tmp/u1o" 2> "$tmp/u1o.err"
rc1o=$?
# REDUNITS: the primary red evidence for the dependent cells (2-5), which
# read the -o output files. Where the verb produced no files (the red tree),
# their failures would otherwise read as "no file" without the reason.
REDUNITS=""
if [ "$rc1o" -ne 0 ] && tr '\n' ' ' < "$tmp/u1o.err" 2>/dev/null | grep -q "unknown command"; then
    REDUNITS=" (the \`push\` verb wrote no unit files: $(tr '\n' ' ' < "$tmp/u1o.err" | head_bytes 160))"
fi
if [ "$rc1" -ne 0 ] || [ "$rc1o" -ne 0 ]; then
    t_fail "1: \`push units\` did not exit 0 (stdout run rc=$rc1, -o run rc=$rc1o) -- on the red tree the \`push\` verb does not exist: $(tr '\n' ' ' < "$tmp/u1.err" | head_bytes 200)"
elif ! grep -qF "jhp-push.service" "$tmp/u1" || ! grep -qF "jhp-push.timer" "$tmp/u1"; then
    t_fail "1: the stdout run does not name BOTH units (jhp-push.service + jhp-push.timer): $(head_bytes 240 "$tmp/u1")"
elif [ ! -f "$od/jhp-push.service" ] || [ ! -f "$od/jhp-push.timer" ]; then
    t_fail "1: the -o run did not write jhp-push.service + jhp-push.timer into $od: $(ls "$od" 2>/dev/null | tr '\n' ' ')"
else
    _extra=$(ls "$od" | grep -v -F -e "jhp-push.service" -e "jhp-push.timer" | wc -l)
    [ -n "$_extra" ] || _extra=0
    if [ "$_extra" -ne 0 ]; then
        t_fail "1: the -o run wrote EXTRA files into $od (the two units only): $(ls "$od" | tr '\n' ' ')"
    else
        t_ok "1: \`push units --config <cfg>\` prints the two units (jhp-push.service + jhp-push.timer) and with -o <dir> writes exactly those two files"
    fi
fi

# --- 2: the service's bytes (oneshot, Nice=10, After, the TICK COMMAND) ------
svc="$od/jhp-push.service"
if [ ! -f "$svc" ]; then
    t_fail "2: no generated service file at $svc (cell 1's -o run did not land)${REDUNITS}: $(head_bytes 240 "$tmp/u1o.err")"
else
    _bad=""
    grep -qF "Type=oneshot" "$svc" || _bad="$_bad Type=oneshot"
    grep -qF "Nice=10" "$svc" || _bad="$_bad Nice=10"
    grep -qF "After=network-online.target" "$svc" || _bad="$_bad After=network-online.target"
    grep -qF "push tick --config" "$svc" || _bad="$_bad the-tick-command-in-ExecStart"
    grep -qF "$tmp/cfg.json" "$svc" || _bad="$_bad the-config-path"
    if [ -n "$_bad" ]; then
        t_fail "2: the generated service is missing:$_bad: $(tr '\n' '|' < "$svc" | head_bytes 300)"
    elif grep -qE "ExecStart=.*\.sh" "$svc"; then
        t_fail "2: the service's ExecStart names a .sh script path -- it must name the TICK COMMAND (\`push tick --config <cfg>\`), not a script (B4): $(grep -F "ExecStart" "$svc" | head_bytes 200)"
    else
        t_ok "2: the service -- Type=oneshot, Nice=10, After=network-online.target, and ExecStart names the TICK COMMAND (\`push tick --config <cfg path>\`), not a .sh script"
    fi
fi

# --- 3: the timer's bytes (OnCalendar = the CONFIGURED value -- SV:1639) -----
# Two DIFFERENT configured values (OC1 here, OC2 under cfg2): a constant
# OnCalendar cannot pass both runs, so the value must come from the config.
od2="$tmp/units-out2"; mkdir -p "$od2" || fixture_fail "units -o dir 2"
tmr="$od/jhp-push.timer"
if [ ! -f "$tmr" ]; then
    t_fail "3: no generated timer file at $tmr (cell 1's -o run did not land)${REDUNITS}: $(head_bytes 240 "$tmp/u1o.err")"
else
    _bad=""
    grep -qF "OnCalendar=$OC1" "$tmr" || _bad="$_bad OnCalendar=$OC1"
    grep -qF "AccuracySec=30s" "$tmr" || _bad="$_bad AccuracySec=30s"
    grep -qF "Persistent=true" "$tmr" || _bad="$_bad Persistent=true"
    grep -qF "WantedBy=timers.target" "$tmr" || _bad="$_bad WantedBy=timers.target"
    if [ -n "$_bad" ]; then
        t_fail "3: the generated timer is missing:$_bad (OnCalendar from the config's host.pushOnCalendar, SV:1639): $(tr '\n' '|' < "$tmr" | head_bytes 300)"
    fi
fi
# The second run under the DIFFERENT configured value: the timer's OnCalendar
# must change with the config (a constant cannot pass both). Where the first
# run already failed (${_bad} non-empty), this part is silent so the cell
# yields exactly one result.
_oc3=""
[ -f "$tmr" ] && [ -z "${_bad:-}" ] && _oc3=first-passed
if [ "$_oc3" = first-passed ]; then
    "$HBIN" push units --config "$tmp/cfg2.json" -o "$od2" \
        < /dev/null > "$tmp/u3b" 2> "$tmp/u3b.err"
    rc3b=$?
    if [ "$rc3b" -ne 0 ]; then
        t_fail "3: \`push units\` under the second config (pushOnCalendar=$OC2) did not exit 0 (rc=$rc3b) -- the OnCalendar must come from the config (SV:1639): $(tr '\n' ' ' < "$tmp/u3b.err" | head_bytes 200)"
    elif ! grep -qF "OnCalendar=$OC2" "$od2/jhp-push.timer" 2>/dev/null; then
        t_fail "3: the second generated timer does not carry the DIFFERENT configured OnCalendar ($OC2) -- a constant schedule cannot pass both runs (SV:1639): $(grep -F OnCalendar "$od2/jhp-push.timer" 2>/dev/null | head_bytes 200)"
    else
        t_ok "3: the timer -- OnCalendar = the CONFIGURED value (host.pushOnCalendar, read from the config under TWO different values so a constant cannot pass), AccuracySec=30s, Persistent=true, WantedBy=timers.target (SV:1639)"
    fi
fi

# --- 4: the names (the jhp- prefix) + this drive's host dir ------------------
if [ ! -f "$svc" ]; then
    t_fail "4: no generated service file at $svc to check the names against (cell 1's -o run did not land)${REDUNITS}"
else
    _bad=""
    [ "$(basename "$svc")" = "jhp-push.service" ] || _bad="$_bad service-basename"
    [ "$(basename "$tmr")" = "jhp-push.timer" ] || _bad="$_bad timer-basename"
    grep -qF "$PH" "$svc" || _bad="$_bad the-host-dir-in-the-service"
    if [ -n "$_bad" ]; then
        t_fail "4: the generated units miss:$_bad -- the names carry the jhp- prefix (NOT the reference's jhd-) and the service carries this drive's host dir ($PH): $(ls "$od" | tr '\n' ' ')"
    else
        t_ok "4: the names carry the jhp- prefix (jhp-push.service / jhp-push.timer, not the reference's jhd-) and the generated service carries this drive's host dir ($PH)"
    fi
fi

# --- 5: the GENERATED marker (not hand-written) ------------------------------
if [ ! -f "$svc" ]; then
    t_fail "5: no generated service file at $svc to check the marker against (cell 1's -o run did not land)${REDUNITS}"
else
    if ! grep -qiE "generated" "$svc"; then
        t_fail "5: the generated service carries no comment marking it GENERATED (the CHANGED marker, B4: the unit is generated, not hand-written): $(tr '\n' '|' < "$svc" | head_bytes 300)"
    else
        t_ok "5: the generated service carries a comment marking it GENERATED, not hand-written (the operator's words, the H7 row)"
    fi
fi

# --- 6: a config WITHOUT the host block refuses, naming it; AND a host block
#     WITHOUT pushOnCalendar refuses exit 2 naming it (SV:1639, no fallback) --
"$HBIN" push units --config "$tmp/cfgnohost.json" \
    < /dev/null > "$tmp/u6" 2> "$tmp/u6.err"
rc6=$?
_pass6=1
if [ "$rc6" -ne 2 ]; then
    _pass6=0
elif ! grep -qiE "no host block" "$tmp/u6.err"; then
    _pass6=0
fi
# The SV:1639 half (same cell): a host block that NAMES no pushOnCalendar
# refuses exit 2 naming `pushOnCalendar` -- NO fallback to a default schedule
# (it may collide with another drive's push on the same host). One t_fail for
# the whole cell (the first failing half names the line).
"$HBIN" push units --config "$tmp/cfgnooc.json" \
    < /dev/null > "$tmp/u6b" 2> "$tmp/u6b.err"
rc6b=$?
_pass6b=1
if [ "$rc6b" -ne 2 ]; then
    _pass6b=0
elif ! grep -qiE "pushOnCalendar" "$tmp/u6b.err"; then
    _pass6b=0
fi
if [ "$_pass6" -eq 1 ] && [ "$_pass6b" -eq 1 ]; then
    t_ok "6: a config without the host block is refused exit 2, naming \`no host block\`; and a host block without pushOnCalendar is refused exit 2, naming \`pushOnCalendar\` (SV:1639: NO fallback -- a default schedule may collide with another drive's push on the same host)"
elif [ "$_pass6" -eq 0 ]; then
    if [ "$rc6" -ne 2 ]; then
        t_fail "6: \`push units\` with a config that has NO host block exited $rc6 (want 2) -- the host commands must not guess a host dir: $(tr '\n' ' ' < "$tmp/u6.err" | head_bytes 200)"
    else
        t_fail "6: the refusal does not name \`no host block\` (on the red tree the line is \`unknown command 'push'\`, not the host-block requirement): $(tr '\n' ' ' < "$tmp/u6.err" | head_bytes 200)"
    fi
else
    if [ "$rc6b" -ne 2 ]; then
        t_fail "6: \`push units\` with a host block WITHOUT pushOnCalendar exited $rc6b (want 2) -- SV:1639: no fallback to a default schedule: $(tr '\n' ' ' < "$tmp/u6b.err" | head_bytes 200)"
    else
        t_fail "6: the absent-pushOnCalendar refusal does not name \`pushOnCalendar\`: $(tr '\n' ' ' < "$tmp/u6b.err" | head_bytes 200)"
    fi
fi

t_done
