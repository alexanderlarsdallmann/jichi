/* jc_hp_gateunits.c - the `gate units` subcommand body (M1159, batch H9b
 * wave 4, task D): the generated form of the transient gate service the
 * watcher's start runs (the design: notes/M1159.md D13; the driver:
 * tests/smoke/harness_gate_run.sh's G30a / G30b cells). The reference's
 * gate-watch.sh systemd-runs a oneshot PER COMMIT (`Description=jichi drive
 * gate on <sha8>`, `--nice=19`); this template, `jhp-gate@.service`, is that
 * oneshot's generated-file twin, which the watcher's start fills with
 * `<sha8>` (into %i).
 *
 * The command reads the config and prints the template to stdout: a
 * `# GENERATED by jichi-harness gate units` marker, `[Unit]` +
 * `Description=jichi drive gate on %i`, `[Service]` + `Type=oneshot` +
 * `Nice=19` and `ExecStart=` the config's gateRun argv, printed VERBATIM
 * (no tokenizing or shell-quoting, the `push units` ExecStart idiom at
 * jc_hp_units.c:139). A config whose `host.gateRun` is absent refuses exit
 * 2 NAMING `host.gateRun` (D13, the note's behaviour-15 pin; NO fallback to
 * a default gate command). The watcher's OWN start path (M1153, the
 * systemd-run stub) is UNCHANGED: the template is the switch-over's
 * generated-file twin and the host decides which form it installs (D13's
 * wave-4 caveat). One owner per file, so this file carries its own refuse
 * helper, file-local (the jc_hp_units.c / jc_hp_watchunits.c idiom). */

#include "jc_hp_gateunits.h"
#include "jc_harness_config.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdarg.h>

#include "jc_snprintf.h"  /* jc_snprintf, never sprintf */

/* A generated unit file never exceeds this (the template is ~1 KB; the
 * gateRun string adds at most PATH_CAP). */
#define UNITS_TEXT_CAP 16384

/* The `gate units` verb's stderr line helper (the push / watch units idiom,
 * file-local twin; the gate verb's prefix). */
static void
gateunits_refuse_line(const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    fprintf(stderr, "jichi-harness: gate units: ");
    vfprintf(stderr, fmt, ap);
    fputc('\n', stderr);
    va_end(ap);
    fflush(stderr);
}

/* Build the jhp-gate@.service text into `dst` (D13's shape: the TRANSIENT
 * gate service template the watcher's start fills with `<sha8>`): the
 * generated marker, [Unit] + Description naming %i, [Service] + Type=oneshot
 * + Nice=19 (the reference's --nice=19) + ExecStart the gateRun argv
 * verbatim. Returns 1 on success, 0 when the buffer is too small or the
 * gateRun is absent. */
static int
build_gate_unit(const char *gate_run, char *dst, size_t cap)
{
    static const char c1a[] =
        "# jhp-gate@.service -- the TRANSIENT gate service template: the "
        "watcher's start fills <sha8> into %i (the reference's gate-watch.sh "
        "systemd-runs a oneshot per commit; this is its generated-file twin, "
        "M1159 D13).\n";
    static const char c1b[] =
        "# GENERATED by jichi-harness gate units (M1159, batch H9b wave 4, "
        "2026-11-11); NOT hand-written: do not edit by hand -- regenerate "
        "it. The host decides which form it installs: the watcher's own "
        "systemd-run start (M1153) or this generated template (D13's "
        "wave-4 caveat).\n";
    static const char body_a[] =
        "[Unit]\n"
        "Description=jichi drive gate on %i\n"
        "\n"
        "[Service]\n"
        "Type=oneshot\n"
        "Nice=19\n";
    static const char exec_fmt[] =
        "ExecStart=%s\n";
    size_t off;
    if (gate_run == NULL || gate_run[0] == '\0') {
        return 0;
    }
    off = strlen(c1a) + strlen(c1b) + strlen(body_a);
    if (off + 1 + strlen(gate_run) + 2 >= cap) {
        return 0;
    }
    memcpy(dst, c1a, strlen(c1a));
    memcpy(dst + strlen(c1a), c1b, strlen(c1b));
    memcpy(dst + strlen(c1a) + strlen(c1b), body_a, strlen(body_a));
    if (jc_snprintf(dst + off, cap - off, exec_fmt, gate_run) < 0) {
        return 0;
    }
    return 1;
}

/* `gate units`: print the generated jhp-gate@.service template to stdout
 * (M1159 D13, minimal per the note -- the port's test pins ONLY the refusal
 * and the template carrying the gateRun argv). `config_path` is REQUIRED;
 * an absent `host.gateRun` refuses exit 2 naming it (behaviour 15). */
int
jc_hp_gateunits_run(const char *config_path, struct jc_arena *a)
{
    struct jc_harness_config cfg;
    char unit[UNITS_TEXT_CAP];
    jc_status st;

    if (config_path == NULL) {
        gateunits_refuse_line("needs --config <file> (the harness "
            "configuration)");
        return 2;
    }
    st = jc_harness_config_load(config_path, &cfg, a);
    if (st != JC_OK) {
        const char *msg = jc_harness_config_error(&cfg);
        gateunits_refuse_line("%s",
            (msg != NULL) ? msg : "could not read the harness config");
        return 2;
    }
    if (cfg.host_gate_run == NULL || cfg.host_gate_run[0] == '\0') {
        gateunits_refuse_line("no host.gateRun in the config -- the "
            "generated jhp-gate@.service's ExecStart is the config's "
            "gateRun argv (M1159 D13, behaviour 15); refused (no fallback "
            "to a default gate command)");
        return 2;
    }
    if (!build_gate_unit(cfg.host_gate_run, unit, sizeof unit)) {
        gateunits_refuse_line("could not build the jhp-gate@.service text "
            "(the gateRun is too long); refused");
        return 1;
    }
    fputs(unit, stdout);
    fflush(stdout);
    return 0;
}
