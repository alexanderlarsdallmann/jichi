/* jc_hp_units.c - the `push units` subcommand body (B4, M1147, batch H7),
 * re-applied from the kept work dropped at the W2 merge (refs/jichi/
 * discarded/parallel-conflict/1793987033-3; the bodies' home was b4's shared
 * jc_harness_push.c, one file per subcommand now -- this owner each). The
 * systemd user units (jhp-push.service / jhp-push.timer), GENERATED not
 * hand-written (notes/M1147.md): the command prints both to stdout, or with
 * `-o <dir>` writes exactly the two files there. The bytes are the
 * reference's shape with THIS drive's names (the jhp- prefix, this drive's
 * host dir) and a CHANGED marker saying the unit is generated, not
 * hand-written; the service's ExecStart names the TICK COMMAND
 * (`push tick --config <cfg>`), not a script path. The timer's OnCalendar is
 * the CONFIGURED value (host.pushOnCalendar, SV:1639): the schedule comes
 * from the config so two drives' pushes never share a minute on the same
 * host; a host block that names no pushOnCalendar refuses exit 2 naming it
 * (NO fallback -- a default schedule may collide with another drive's push
 * on the same host). The `push` verb's host-block refusal lives here (the
 * run-drive body, jc_hp_rundrive.c, carries its own file-local twin -- one
 * owner per file, no cross-file private symbols). */

#include "jc_harness_push.h"
#include "jc_harness_config.h"
#include "jc_snprintf.h"
#include "jc_mem.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>   /* readlink */

/* Paths hang off the config's dir / the host dir; give the joins room, the
 * same bound jc_harness_push.c's PATH_CAP uses for the mirror joins. */
#define PATH_CAP 4352

/* A generated unit file never exceeds this (the reference's are ~1 KB; the
 * host dir / config path add at most PATH_CAP each). */
#define UNITS_TEXT_CAP 16384

/* The `push` verb's refusal helper: the host commands (units, run-drive) are
 * host-side by construction, so a config with no usable `host` block is a
 * USAGE refusal (exit 2) naming `no host block`, not a guess (the note's
 * "the host commands are host-side by construction ... must not guess one").
 * This is the ONE site both bodies use for that refusal. */
static int
push_refuse_host(const struct jc_harness_config *cfg)
{
    if (cfg->host_dir_present == 0 ||
        cfg->host_dir == NULL || cfg->host_dir[0] == '\0') {
        fprintf(stderr, "jichi-harness: push: no host block in the config "
                "-- the host push commands are host-side by construction; "
                "a config that names no host dir must not guess one (the "
                "host object: pushHome, image, dir)\n");
        return 2;
    }
    return 0;
}

/* The `push` verb's stderr/stdout line helpers (b4's refuse/say, the push
 * verb's prefix -- NOT mirror's; M1056's static refuse is file-local to
 * jc_harness_push.c). */
static void
push_refuse_line(const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    fprintf(stderr, "jichi-harness: push: ");
    vfprintf(stderr, fmt, ap);
    fputc('\n', stderr);
    va_end(ap);
    fflush(stderr);
}

static void
push_say_line(const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    fputs("push: ", stdout);
    vfprintf(stdout, fmt, ap);
    fputc('\n', stdout);
    va_end(ap);
    fflush(stdout);
}

/* The harness's own executable path for the unit's ExecStart (readlink
 * /proc/self/exe, the M1053 idiom already used by self_exe in
 * jc_harness_push.c; that one is file-local, so this file carries its own).
 * Returns 1 on success. */
static int
units_self_path(char *out, size_t cap)
{
    char buf[PATH_CAP];
    ssize_t n;
    n = readlink("/proc/self/exe", buf, sizeof buf - 1);
    if (n <= 0 || n >= (ssize_t)sizeof buf) {
        return 0;
    }
    buf[n] = '\0';
    if (jc_snprintf(out, cap, "%s", buf) >= (int)cap) {
        return 0;
    }
    return 1;
}

/* Build the jhp-push.service text into `dst` (the reference's shape with
 * THIS drive's names: the jhp- prefix, this drive's host dir, a GENERATED
 * marker, and an ExecStart that names the TICK COMMAND --
 * `push tick --config <cfg>` -- not a script path). The push home (where the
 * tick writes push.log / push-tick.out / push.lock) is carried in a comment
 * so the unit names this drive's host. Returns 1 on success, 0 when the
 * buffer is too small. */
static int
build_units_service(const char *harness, const char *cfg_path,
                    const char *push_home, char *dst, size_t cap)
{
    static const char c1a[] =
        "# jhp-push.service -- GENERATED by `jichi-harness push units` "
        "(M1147, batch H7, 2026-11-06); NOT hand-written: do not edit by "
        "hand -- regenerate it.\n";
    static const char c1b_fmt[] =
        "# The harness port drive's host push (the user-level oneshot). "
        "Runs `<harness> push tick --config <config>`: the team mirror push "
        "(`mirror push`) + the records push, from the host (the container "
        "never holds the git token; option B). Push home (logs push.log, "
        "push-tick.out, lock push.lock): %s. Started by jhp-push.timer; "
        "never by hand while a push runs (the tick takes push.lock "
        "anyway).\n";
    static const char body_a[] =
        "[Unit]\n"
        "Description=jichi harness port drive: host push (push tick)\n"
        "After=network-online.target\n"
        "\n"
        "[Service]\n"
        "Type=oneshot\n"
        "Nice=10\n";
    static const char exec_fmt[] =
        "ExecStart=%s push tick --config %s\n";
    char c1b[PATH_CAP + 256];
    size_t off = 0;
    int w;
    const char *ph = (push_home != NULL) ? push_home : "";

    w = jc_snprintf(c1b, sizeof c1b, c1b_fmt, ph);
    if (w < 0 || (size_t)w >= sizeof c1b) {
        return 0;
    }
    /* The two segments, then the ExecStart line with its values. */
    off = (size_t)strlen(c1a) + (size_t)strlen(c1b) + (size_t)strlen(body_a);
    if (off + 1 + strlen(harness) + 1 + strlen(cfg_path) + 2 >= cap) {
        return 0;
    }
    memcpy(dst, c1a, strlen(c1a));
    memcpy(dst + strlen(c1a), c1b, strlen(c1b));
    memcpy(dst + strlen(c1a) + strlen(c1b), body_a, strlen(body_a));
    w = jc_snprintf(dst + off, cap - off, exec_fmt, harness, cfg_path);
    if (w < 0 || (size_t)w >= cap - off) {
        return 0;
    }
    return 1;
}

/* Build the jhp-push.timer text into `dst` (the reference's shape with
 * THIS drive's names: the jhp- prefix; the AccuracySec / Persistent /
 * WantedBy values IDENTICAL to the reference). The OnCalendar is the
 * CONFIGURED value (host.pushOnCalendar, SV:1639): the schedule comes from
 * the config so two drives' pushes never share a minute on the same host --
 * no fixed offset holds (the loop's fetch minute moves with each run's
 * start), so a constant schedule here is the defect the config read fixes.
 * Returns 1 on success, 0 when the buffer is too small. */
static int
build_units_timer(const char *oncalendar, char *dst, size_t cap)
{
    static const char head[] =
        "# jhp-push.timer -- GENERATED by `jichi-harness push units` "
        "(M1147, batch H7, 2026-11-06); NOT hand-written: do not edit by "
        "hand -- regenerate it.\n"
        "# The schedule comes from the config (host.pushOnCalendar) so two "
        "drives' pushes never share a minute on the same host. Persistent: "
        "a tick missed while the machine was off runs at the next boot.\n"
        "[Unit]\n"
        "Description=jichi harness port drive: host push (scheduled)\n"
        "\n"
        "[Timer]\n";
    static const char oncal_fmt[] =
        "OnCalendar=%s\n";
    static const char tail[] =
        "AccuracySec=30s\n"
        "Persistent=true\n"
        "\n"
        "[Install]\n"
        "WantedBy=timers.target\n";
    size_t off;
    if (oncalendar == NULL || oncalendar[0] == '\0') {
        return 0;
    }
    if (strlen(head) + strlen(oncal_fmt) + strlen(oncalendar) + 1 +
        strlen(tail) + 1 >= cap) {
        return 0;
    }
    memcpy(dst, head, strlen(head));
    off = strlen(head);
    off += (size_t)jc_snprintf(dst + off, cap - off, oncal_fmt, oncalendar);
    memcpy(dst + off, tail, strlen(tail));
    dst[off + strlen(tail)] = '\0';
    return 1;
}

/* `push units`: the systemd unit files, generated not hand-written (B4).
 * The dispatch passes the `-o <dir>` value in `positional` (NULL when
 * absent); `rest`/`n_rest` are unused for units. Default: print both
 * generated units to stdout. With `-o`: write the two files under the dir
 * (creating nothing but the files) and print a confirmation line. A config
 * with no usable host block refuses exit 2 naming `no host block` (the one
 * site, push_refuse_host). */
int
jc_harness_push_units_run(const char *config_path, const char *positional,
                          struct jc_arena *a, const char **rest, int n_rest)
{
    struct jc_harness_config cfg;
    char harness[PATH_CAP];
    char svc[UNITS_TEXT_CAP];
    char tmr[UNITS_TEXT_CAP];
    const char *out_dir;
    char svcpath[PATH_CAP + 32];
    char tmrpath[PATH_CAP + 32];
    jc_status st;
    int rc;
    (void)rest;
    (void)n_rest;

    if (config_path == NULL) {
        push_refuse_line("needs --config <file> (the harness configuration)");
        return 2;
    }
    st = jc_harness_config_load(config_path, &cfg, a);
    if (st != JC_OK) {
        const char *msg = jc_harness_config_error(&cfg);
        push_refuse_line("%s",
            (msg != NULL) ? msg : "could not read the harness config");
        return 2;
    }
    rc = push_refuse_host(&cfg);
    if (rc != 0) {
        return rc;
    }
    if (!units_self_path(harness, sizeof harness)) {
        push_refuse_line("could not resolve the harness's own path "
            "(readlink /proc/self/exe failed); the unit's ExecStart cannot "
            "name the tick command; refused");
        return 1;
    }
    if (cfg.host_push_oncalendar == NULL ||
        cfg.host_push_oncalendar[0] == '\0') {
        push_refuse_line("the host block names no pushOnCalendar -- the "
            "generated jhp-push.timer's schedule comes from the config "
            "(host.pushOnCalendar) so two drives' pushes never share a "
            "minute on the same host; refused (no fallback to a default "
            "schedule)");
        return 2;
    }
    if (!build_units_service(harness, config_path, cfg.host_push_home, svc,
                            sizeof svc)) {
        push_refuse_line("could not build the jhp-push.service text "
            "(the paths are too long); refused");
        return 1;
    }
    if (!build_units_timer(cfg.host_push_oncalendar, tmr, sizeof tmr)) {
        push_refuse_line("could not build the jhp-push.timer text; refused");
        return 1;
    }
    out_dir = positional;
    if (out_dir == NULL || out_dir[0] == '\0') {
        /* Default: both units to stdout, service first, timer second,
         * separated by a blank line. */
        fputs(svc, stdout);
        fputc('\n', stdout);
        fputs(tmr, stdout);
        fflush(stdout);
        return 0;
    }
    /* -o <dir>: write the two files (exactly those two, nothing else) and
     * print one confirmation line. */
    if (jc_snprintf(svcpath, sizeof svcpath, "%s/jhp-push.service", out_dir)
        >= (int)sizeof svcpath ||
        jc_snprintf(tmrpath, sizeof tmrpath, "%s/jhp-push.timer", out_dir)
        >= (int)sizeof tmrpath) {
        push_refuse_line("the -o directory path is too long to build the "
            "unit file paths; refused");
        return 2;
    }
    if (jc_write_file(svcpath, svc, (jc_size)strlen(svc)) != JC_OK) {
        push_refuse_line("could not write %s (the -o directory is not "
            "writable?); refused", svcpath);
        return 1;
    }
    if (jc_write_file(tmrpath, tmr, (jc_size)strlen(tmr)) != JC_OK) {
        push_refuse_line("could not write %s (the -o directory is not "
            "writable?); refused", tmrpath);
        return 1;
    }
    push_say_line("wrote the two generated units: %s and %s", svcpath, tmrpath);
    return 0;
}
